#!/usr/bin/env bash
# Generate the demo PKI (ECDSA P-256): CA, OTA server and device certificates,
# and include/certs.h with the CA, device certificate and device key in DER.
set -e
cd "$(dirname "$0")"

openssl ecparam -name prime256v1 -genkey -noout -out ca-key.pem
openssl req -x509 -new -key ca-key.pem -sha256 -days 3650 \
    -subj "/O=wolfSSL Demo/CN=C5 OTA Demo CA" -out ca-cert.pem

openssl ecparam -name prime256v1 -genkey -noout -out server-key.pem
openssl req -new -key server-key.pem -subj "/O=wolfSSL Demo/CN=ota-server" \
    -out server.csr
printf 'basicConstraints=critical,CA:FALSE\nkeyUsage=critical,digitalSignature\nextendedKeyUsage=serverAuth\n' > server.ext
openssl x509 -req -in server.csr -CA ca-cert.pem -CAkey ca-key.pem \
    -CAcreateserial -sha256 -days 3650 -extfile server.ext -out server-cert.pem

openssl ecparam -name prime256v1 -genkey -noout -out device-key.pem
openssl req -new -key device-key.pem -subj "/O=wolfSSL Demo/CN=nucleo-c5a3zg" \
    -out device.csr
printf 'basicConstraints=critical,CA:FALSE\nkeyUsage=critical,digitalSignature\nextendedKeyUsage=clientAuth\n' > device.ext
openssl x509 -req -in device.csr -CA ca-cert.pem -CAkey ca-key.pem \
    -CAcreateserial -sha256 -days 3650 -extfile device.ext -out device-cert.pem

openssl x509 -in ca-cert.pem -outform DER -out ca-cert.der
openssl x509 -in device-cert.pem -outform DER -out device-cert.der
openssl ec -in device-key.pem -outform DER -out device-key.der 2>/dev/null
rm -f server.csr device.csr server.ext device.ext ca-cert.srl

{
    echo "/* Generated by certs/gen_certs.sh - demo PKI, not for production. */"
    echo "#ifndef DEMO_CERTS_H"
    echo "#define DEMO_CERTS_H"
    for f in ca-cert device-cert device-key; do
        n=$(echo "$f" | tr '-' '_')_der
        echo "static const unsigned char ${n}[] = {"
        xxd -i < "$f.der" | sed 's/^/    /'
        echo "};"
    done
    echo "#endif"
} > ../include/certs.h
echo "Wrote $(cd .. && pwd)/include/certs.h"
